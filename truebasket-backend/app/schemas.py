class OriginalProduct(BaseModel):
    """Structured product identification extracted from packaging."""

    brand: Optional[str] = Field(None, description="Identified brand name (e.g. YogaBar, Kellogg's)")
    product_name: Optional[str] = Field(None, description="Identified product title (e.g. Super Muesli)")
    name: Optional[str] = Field(None, description="Alias for product_name for frontend compatibility")
    variant: Optional[str] = Field(None, description="Flavor or variant (e.g. Fruits, Nuts & Seeds)")

    @model_validator(mode="before")
    @classmethod
    def sync_name_and_product_name(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if data.get("product_name") and not data.get("name"):
                data["name"] = data["product_name"]
            elif data.get("name") and not data.get("product_name"):
                data["product_name"] = data["name"]
        return data
    net_weight: Optional[str] = Field(None, description="Declared net weight on packaging (e.g. 400g)")
    serving_size: Optional[str] = Field(None, description="Declared serving size (e.g. 40g)")
    ingredient_list: List[str] = Field(default_factory=list, description="Visible ingredients parsed from packaging")
    declared_percentages: Dict[str, float] = Field(
        default_factory=dict,
        description="Declared ingredient percentages stamped on packaging (e.g. {'Rolled Oats': 50.0})",
    )
    nutrition_facts: Dict[str, Any] = Field(
        default_factory=dict,
        description="Nutrition facts per 100g or per serving (energy, protein, sugar, fibre, fat)",
    )
    allergen_warnings: List[str] = Field(
        default_factory=list,
        description="Explicit allergen or cross-contamination warnings",
    )
    barcode: Optional[str] = Field(None, description="EAN/UPC barcode number if legible")
    fssai_license: Optional[str] = Field(None, description="FSSAI license number if legible")
    manufacturer: Optional[str] = Field(None, description="Manufacturer/marketer name and address")
    panel_type: str = Field(
        default="unclear",
        description="'front_of_pack', 'back_of_pack', 'nutrition_and_ingredients', 'full_wrap', or 'unclear'",
    )
    ingredient_panel_missing: bool = Field(
        default=False,
        description="True if the uploaded image lacks the ingredients/nutrition panel",
    )
    image_reference: Optional[str] = Field(default="user_uploaded_image", description="Image origin")
    visual_extraction: Optional[VisualLabelExtraction] = Field(None, description="Visual label extraction metadata")
    name: Optional[str] = Field(None, description="Frontend alias for product_name")
    quantity: Optional[str] = Field(None, description="Frontend alias for net_weight")
    package_size: Optional[str] = Field(None, description="Package size or quantity")
    ingredients_text: Optional[str] = Field(None, description="Raw visible ingredients text")
    visible_claims: List[str] = Field(default_factory=list, description="Marketing claims visible on pack")
    unreadable_fields: List[str] = Field(default_factory=list, description="Fields present but illegible or blurry")
    evidence_notes: Optional[str] = Field(None, description="Diagnostic notes about visible evidence")

    @model_validator(mode="after")
    def sync_frontend_fields(self) -> "OriginalProduct":
        if not self.name and self.product_name:
            self.name = self.product_name
        elif not self.product_name and self.name:
            self.product_name = self.name
        if not self.quantity and self.net_weight:
            self.quantity = self.net_weight
        elif not self.net_weight and self.quantity:
            self.net_weight = self.quantity
        if not self.package_size and self.net_weight:
            self.package_size = self.net_weight
        elif not self.net_weight and self.package_size:
            self.net_weight = self.package_size
        return self


